#!/usr/bin/env node
/**
 * gen-bytecode-json.ts
 *
 * Generates src/grey/bytecode.json from the Forge artifact at
 * contracts/out/GreyPayroll.sol/GreyPayroll.json.
 *
 * Fields produced:
 *   bytecode               — deployment bytecode (0x-prefixed hex)
 *   deployedBytecode       — runtime bytecode (0x-prefixed hex)
 *   deployedBytecodeKeccak — keccak256 of the runtime bytecode
 *
 * The keccak256 is computed deterministically from the Forge output.
 * The contract has no immutable constructor arguments, so the runtime
 * bytecode is identical across all deployments compiled with the same
 * compiler/settings — exact comparison is valid.
 *
 * Pinned compiler settings (foundry.toml):
 *   solc = "0.8.28"
 *   evm_version = "cancun"
 *   optimizer = true, optimizer_runs = 200
 *
 * Usage (portable — requires only node ≥ 18 and viem in node_modules):
 *   node --import tsx/esm scripts/gen-bytecode-json.ts
 *   # or with bun:
 *   bun scripts/gen-bytecode-json.ts
 *
 * The package.json contracts:gen-bytecode script wraps this portably.
 * Run after `forge build` whenever GreyPayroll.sol changes.
 * Commit the resulting src/grey/bytecode.json so the browser can verify
 * deployed contracts without running Forge inside the frontend build.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

// __dirname equivalent for ESM (works in both node and bun)
const _dir: string = (() => {
  // Bun exposes import.meta.dir; node ESM does not.
  const metaDir: unknown = (import.meta as ImportMeta & { dir?: unknown }).dir
  if (typeof metaDir === 'string') return metaDir
  return dirname(fileURLToPath(import.meta.url))
})()

const ARTIFACT_PATH = resolve(_dir, '../contracts/out/GreyPayroll.sol/GreyPayroll.json')
const OUTPUT_PATH   = resolve(_dir, '../src/grey/bytecode.json')

interface ForgeArtifact {
  bytecode: { object: string }
  deployedBytecode: { object: string }
}

function toHex(s: string): string {
  return s.startsWith('0x') ? s : `0x${s}`
}

function keccak256Hex(hex: string): string {
  const buf = Buffer.from(hex.replace(/^0x/, ''), 'hex')
  // Use viem's keccak256 (available in node_modules after install).
  // createRequire allows require() from an ESM module.
  const req = createRequire(import.meta.url)
  try {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const { keccak256: viemKeccak } = req('viem') as { keccak256: (b: Uint8Array) => string }
    return viemKeccak(new Uint8Array(buf))
  } catch {
    console.error(
      'ERROR: viem not found in node_modules. ' +
      'Run `npm install` (or `bun install`) first, then retry.',
    )
    process.exit(1)
  }
}

// Read artifact
let artifact: ForgeArtifact
try {
  artifact = JSON.parse(readFileSync(ARTIFACT_PATH, 'utf8')) as ForgeArtifact
} catch {
  console.error(
    `ERROR: Could not read Forge artifact at ${ARTIFACT_PATH}.\n` +
    `Run 'forge build' first, then retry.`,
  )
  process.exit(1)
}

const bytecode         = toHex(artifact.bytecode.object)
const deployedBytecode = toHex(artifact.deployedBytecode.object)
const deployedBytecodeKeccak = keccak256Hex(deployedBytecode)

const output = {
  bytecode,
  deployedBytecode,
  deployedBytecodeKeccak,
  _comment: [
    'Generated by scripts/gen-bytecode-json.ts from contracts/out/GreyPayroll.sol/GreyPayroll.json.',
    'Compiler: solc 0.8.28, evm_version=cancun, optimizer=true, runs=200.',
    'deployedBytecodeKeccak = keccak256(deployedBytecode) — used by ContractSetup to verify',
    'that a pasted/deployed address contains the canonical GreyPayroll runtime code.',
    'Re-generate after any contract change: npm run contracts:gen-bytecode',
  ].join(' '),
}

writeFileSync(OUTPUT_PATH, JSON.stringify(output, null, 2) + '\n', 'utf8')
console.log(`Wrote ${OUTPUT_PATH}`)
console.log(`  bytecode length: ${bytecode.length} chars (${(bytecode.length - 2) / 2} bytes)`)
console.log(`  deployedBytecodeKeccak: ${deployedBytecodeKeccak}`)
